/**
 * HermesRuntime — drives a Hermes Agent CLI process per message (turn-based).
 *
 * Each agent gets an isolated HERMES_HOME under its dir (own config, memory,
 * skills). The config points Hermes at the agent's provider (providerConfig
 * baseUrl/apiKey/model — e.g. DeepSeek) and registers the agentslack MCP
 * bridge, so Hermes' own memory/skills loop works per agent.
 *
 * Requires the `hermes` binary on the host (HERMES_CLI_PATH to override).
 * Missing binary degrades gracefully: status -> offline, error activity.
 */
import { execFile } from 'child_process'
import path from 'path'
import fs from 'fs'
import type { AgentRuntime } from './interface'
import type {
  AgentConfig,
  AgentRuntimeType,
  IncomingMessage,
  ActivityCallback,
  SessionStatusCallback,
  StatusCallback,
} from './types'
import { executeTool, internalBaseUrl } from './tool-executor'

const HERMES_CLI = process.env.HERMES_CLI_PATH || 'hermes'
const MCP_BRIDGE_PATH = path.join(process.cwd(), 'server', 'mcp-bridge.ts')
const TURN_TIMEOUT_MS = 300_000

function buildSystemPrompt(agent: AgentConfig): string {
  return `You are ${agent.name}, an agent inside AgentSlack, a Slack-like workspace for AI agents.
${agent.soulMd ? `## Identity\n${agent.soulMd}` : ''}
## Rules
- You reply with plain text. Your final reply is automatically delivered to the channel/thread by the runtime.
- You have MCP tools available (send_message, read_history, check_messages, list_channels, list_agents, list_projects, list_tasks, create_tasks, claim_tasks, unclaim_task, update_task_status, get_task_context). Use them when useful.
- Never fabricate tool results; if a tool errors, say so.
- Keep replies concise and useful.`
}

function stripAnsi(text: string): string {
  // eslint-disable-next-line no-control-regex
  return text.replace(/\x1b\[[0-9;]*m/g, '').trim()
}

export class HermesRuntime implements AgentRuntime {
  readonly type: AgentRuntimeType = 'hermes'

  private configs = new Map<string, AgentConfig>()
  private stopped = new Set<string>()
  private onStatusChange: StatusCallback | null = null
  private onSessionStatusChange: SessionStatusCallback | null = null
  private onActivity: ActivityCallback | null = null

  setStatusCallback(cb: StatusCallback) { this.onStatusChange = cb }
  setSessionStatusCallback(cb: SessionStatusCallback) { this.onSessionStatusChange = cb }
  setActivityCallback(cb: ActivityCallback) { this.onActivity = cb }

  /** Write the agent's isolated Hermes config (HERMES_HOME). */
  private writeHermesHome(agent: AgentConfig): string {
    const home = path.join(agent.dirPath, '.hermes-home')
    fs.mkdirSync(home, { recursive: true })
    fs.mkdirSync(path.join(home, 'memory'), { recursive: true })
    fs.mkdirSync(path.join(home, 'skills'), { recursive: true })

    const baseUrl = agent.providerConfig?.baseUrl || process.env.HERMES_BASE_URL || ''
    const apiKey = agent.providerConfig?.apiKey || process.env.HERMES_API_KEY || ''
    const model = agent.providerConfig?.model || agent.model
    const internalUrl = internalBaseUrl()

    const config = [
      '# Generated by AgentSlack HermesRuntime',
      'model:',
      `  default: ${model}`,
      '  provider: custom:agentslack',
      `  base_url: ${baseUrl}`,
      'custom_providers:',
      '  agentslack:',
      `    base_url: ${baseUrl}`,
      `    api_key: ${apiKey}`,
      'mcp_servers:',
      '  agentslack:',
      '    command: npx',
      `    args: ["tsx", "${MCP_BRIDGE_PATH}"]`,
      '    env:',
      `      AGENT_ID: ${agent.id}`,
      `      AGENTSLACK_INTERNAL_URL: ${internalUrl}`,
      '',
    ].join('\n')

    fs.writeFileSync(path.join(home, 'config.yaml'), config, { mode: 0o600 })
    return home
  }

  startAgent(agent: AgentConfig) {
    this.configs.set(agent.id, agent)
    this.stopped.delete(agent.id)
    try {
      this.writeHermesHome(agent)
      this.onStatusChange?.(agent.id, 'online')
    } catch (err) {
      console.error(`[HermesRuntime] failed to init ${agent.name}:`, err)
      this.onStatusChange?.(agent.id, 'offline')
    }
  }

  private async postReply(agentId: string, content: string, msg: IncomingMessage) {
    await executeTool(agentId, 'send_message', {
      channelId: msg.channelId,
      threadId: msg.threadId ?? undefined,
      content,
    })
  }

  deliverMessage(agentId: string, message: IncomingMessage): boolean {
    const agent = this.configs.get(agentId)
    if (!agent || this.stopped.has(agentId)) return false

    const home = path.join(agent.dirPath, '.hermes-home')
    const prompt = [
      buildSystemPrompt(agent),
      '',
      `[Channel: ${message.channelId}]`,
      message.threadId ? `[Thread: ${message.threadId}]` : null,
      `${message.senderName}: ${message.content}`,
    ].filter(Boolean).join('\n')

    this.onActivity?.(agentId, { type: 'text', text: 'thinking…', timestamp: Date.now() })

    execFile(
      HERMES_CLI,
      ['chat', '-p', prompt, '-Q'],
      { env: { ...process.env, HERMES_HOME: home }, timeout: TURN_TIMEOUT_MS, maxBuffer: 10 * 1024 * 1024 },
      (err, stdout, stderr) => {
        if (err) {
          const missing = (err as NodeJS.ErrnoException).code === 'ENOENT'
          console.error(`[HermesRuntime] ${agent.name} hermes failed:`, missing ? 'hermes binary not found' : err.message)
          this.onStatusChange?.(agentId, 'offline')
          this.onActivity?.(agentId, { type: 'system', subtype: 'error', timestamp: Date.now() })
          return
        }
        const reply = stripAnsi(stdout) || stripAnsi(stderr)
        if (!reply) return
        this.onActivity?.(agentId, { type: 'text', text: reply.slice(0, 200), timestamp: Date.now() })
        this.postReply(agentId, reply, message).catch((e) =>
          console.error(`[HermesRuntime] ${agent.name} reply post failed:`, e),
        )
      },
    )
    return true
  }

  isReady(agentId: string): boolean { return this.configs.has(agentId) }
  isRunning(agentId: string): boolean { return this.configs.has(agentId) && !this.stopped.has(agentId) }
  getRunningCount(): number { return this.configs.size }
  getStatuses() {
    return [...this.configs.entries()].map(([agentId, config]) => ({
      agentId,
      name: config.name,
      ready: true,
      running: this.isRunning(agentId),
    }))
  }
  stopAgent(agentId: string) { this.configs.delete(agentId) }
  stopAgentManual(agentId: string) {
    this.stopped.add(agentId)
    this.configs.delete(agentId)
    this.onStatusChange?.(agentId, 'offline')
  }
  startAgentManual(agentId: string) {
    this.stopped.delete(agentId)
    const agent = this.configs.get(agentId)
    if (agent) this.startAgent(agent)
  }
  restartAgent(agentId: string) {
    this.stopped.delete(agentId)
    const agent = this.configs.get(agentId)
    if (agent) this.startAgent(agent)
  }
  updateConfig(agentId: string, updates: Partial<AgentConfig>) {
    const config = this.configs.get(agentId)
    if (config) {
      const next = { ...config, ...updates }
      this.configs.set(agentId, next)
      try {
        this.writeHermesHome(next)
      } catch (err) {
        console.error(`[HermesRuntime] re-init failed for ${agentId}:`, err)
      }
    }
  }
  stopAll() {
    this.configs.clear()
    this.stopped.clear()
  }
}
